// Generates the README call-to-action button with outlined text, so it renders identically on every system.
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';
import { faRobot } from '@fortawesome/free-solid-svg-icons';
import opentype from 'opentype.js';

const require = createRequire(import.meta.url);
const output = fileURLToPath(new URL('../docs/create-colophon.svg', import.meta.url));
const font = weight => {
  const file = readFileSync(require.resolve(`@fontsource/inter/files/inter-latin-${weight}-normal.woff`));
  return opentype.parse(file.buffer.slice(file.byteOffset, file.byteOffset + file.byteLength));
};
const faVersion = require('@fortawesome/free-solid-svg-icons/package.json').version;
const interVersion = require('@fontsource/inter/package.json').version;

const title = 'Create your colophon';
const subtitle = 'Guided self-assessment of AI use in code';
const label = `${title}. ${subtitle}.`;
const categoryColors = ['#a15a76', '#8a5f97', '#6763a6', '#4a7fa6'];

const height = 56;
const radius = 12;
const tile = { x: 12, y: 9, size: 34 };
const textX = tile.x + tile.size + 13;
const heading = { font: font(700), size: 16, y: 24 };
const caption = { font: font(500), size: 12, y: 40 };

// Place glyphs by advance width only. opentype.js 2.0 cannot apply Inter's contextual features or read its
// kerning (stored in GPOS extension lookups), so the text is set unkerned; at this size the difference is minor.
function setText({ font, size, y }, text) {
  const scale = size / font.unitsPerEm;
  let cursor = textX;
  const paths = [];
  for (const glyph of Array.from(text, character => font.charToGlyph(character))) {
    paths.push(glyph.getPath(cursor, y, size).toPathData(2));
    cursor += glyph.advanceWidth * scale;
  }
  return { d: paths.join(''), width: cursor - textX };
}
const headingText = setText(heading, title);
const captionText = setText(caption, subtitle);
const headingWidth = headingText.width;
const captionWidth = captionText.width;
const arrowRadius = 13;
const arrowX = Math.ceil(textX + Math.max(headingWidth, captionWidth) + 18 + arrowRadius);
const width = arrowX + arrowRadius + 14;


const [robotWidth, robotHeight, , , robotPath] = faRobot.icon;
const robotSize = 21;
const robotScale = robotSize / Math.max(robotWidth, robotHeight);
const robotX = tile.x + (tile.size - robotWidth * robotScale) / 2;
const robotY = tile.y + (tile.size - robotHeight * robotScale) / 2;

const stripY = height - 4;
const segment = width / categoryColors.length;
const strip = categoryColors
  .map((fill, index) => `<rect x="${(index * segment).toFixed(2)}" y="${stripY}" width="${segment.toFixed(2)}" height="4" fill="${fill}"/>`)
  .join('\n    ');

const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="${width}" height="${height}" viewBox="0 0 ${width} ${height}" role="img" aria-label="${label}">
  <title>${label}</title>
  <!-- Generated by scripts/generate-button.mjs. -->
  <!-- Robot icon by Font Awesome Free ${faVersion} (https://fontawesome.com), CC BY 4.0 (https://creativecommons.org/licenses/by/4.0/). -->
  <!-- Text outlined from Inter ${interVersion} (https://rsms.me/inter/), SIL Open Font License 1.1. -->
  <defs>
    <linearGradient id="bg" x1="0" y1="0" x2="1" y2="1">
      <stop offset="0" stop-color="#74527f"/>
      <stop offset="1" stop-color="#54395e"/>
    </linearGradient>
    <clipPath id="shape"><rect width="${width}" height="${height}" rx="${radius}"/></clipPath>
  </defs>
  <g clip-path="url(#shape)">
    <rect width="${width}" height="${height}" fill="url(#bg)"/>
    ${strip}
  </g>
  <rect x=".5" y=".5" width="${width - 1}" height="${height - 1}" rx="${radius - 0.5}" fill="none" stroke="#fff" stroke-opacity=".2"/>
  <rect x="${tile.x}" y="${tile.y}" width="${tile.size}" height="${tile.size}" rx="9" fill="#fff" fill-opacity=".15"/>
  <path fill="#fff" transform="translate(${robotX.toFixed(2)} ${robotY.toFixed(2)}) scale(${robotScale.toFixed(5)})" d="${robotPath}"/>
  <path fill="#fff" d="${headingText.d}"/>
  <path fill="#fff" fill-opacity=".8" d="${captionText.d}"/>
  <circle cx="${arrowX}" cy="${tile.y + tile.size / 2}" r="${arrowRadius}" fill="#fff" fill-opacity=".16"/>
  <path d="M${arrowX - 5} ${tile.y + tile.size / 2}h10m-4.2-4.2 4.2 4.2-4.2 4.2" fill="none" stroke="#fff" stroke-width="1.9" stroke-linecap="round" stroke-linejoin="round"/>
</svg>
`;

writeFileSync(output, svg);
console.log(`Wrote ${output} (${width}×${height}).`);
